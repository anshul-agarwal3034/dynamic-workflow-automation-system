  function resolveKey(obj, path) {
    if (!obj || !path) return null;
    if (obj[path] !== undefined) return obj[path];
    var parts = path.split('.');
    var cur = obj;
    for (var i = 0; i < parts.length; i++) {
      if (cur && typeof cur === 'object' && parts[i] in cur) {
        cur = cur[parts[i]];
      } else {
        return null;
      }
    }
    return typeof cur === 'string' ? cur : null;
  }

  function t(key, lang) {
    var activeLang = lang || global.currentLanguage || (typeof localStorage !== 'undefined' && (localStorage.getItem('formpilotx_lang') || localStorage.getItem('formpilot_lang'))) || 'en';
    var dict = translations[activeLang] || translations.en;
    var res = resolveKey(dict, key);
    if (res !== null) return res;
    var fallback = resolveKey(translations.en, key);
    if (fallback !== null) return fallback;
    return key;
  }

